def load_nodes(path: Path) -> list[dict]:
    with open(path) as f:
        return yaml.safe_load(f)["nodes"]


def load_layers(path: Path) -> list[dict]:
    with open(path) as f:
        return yaml.safe_load(f)["layers"]


def load_corrections(path: Path) -> list[dict]:
    if not path or not path.exists():
        return []
    with open(path) as f:
        data = yaml.safe_load(f)
    return data.get("corrections", []) if data else []


# ---------------------------------------------------------------------------
# Correction Engine
# ---------------------------------------------------------------------------

def get_applicable_corrections(corrections, node_id, layer_id, function_id, model_tier):
    applicable = []
    for c in corrections:
        target = c.get("applies_to", "")
        rule = c.get("rule", "")
        if not rule:
            continue
        if target == "all":
            applicable.append(rule)
        elif target.startswith("node:") and target.split(":")[1] == node_id:
            applicable.append(rule)
        elif target.startswith("layer:") and target.split(":")[1] == layer_id:
            applicable.append(rule)
        elif target.startswith("function:") and target.split(":")[1] == function_id:
            applicable.append(rule)
        elif target.startswith("model_tier:") and target.split(":")[1] == model_tier:
            applicable.append(rule)
    return applicable


# ---------------------------------------------------------------------------
# Meta-Prompt — asks LLM for ONLY the prompt text, as JSON
# ---------------------------------------------------------------------------

def build_meta_prompt(node: dict, layer: dict, corrections: list[str]) -> str:
    focus_areas = "\n".join(f"  - {fa}" for fa in node.get("focus_areas", []))

    word_limit = "under 150 words" if layer["model_tier"] == "small" else \
                 "under 250 words" if layer["model_tier"] == "medium" else \
                 "under 350 words"

    correction_block = ""
    if corrections:
        rules = "\n".join(f"  - {r}" for r in corrections)
        correction_block = f"""
MANDATORY RULES for the prompt you generate:
{rules}
"""

    return f"""Write an LLM prompt template for a consciousness architecture processing function.

This function analyzes conversation exchanges at the intersection of:
- NODE: {node['name']} — {node['domain']}
- LAYER: {layer['name']} (depth {layer['depth']}) — {layer['instruction']}

The node asks: "{node['core_question']}"
The node focuses on:
{focus_areas}

The layer instruction: "{layer['instruction']}"
Output style: {layer['output_style']}

Node example output: "{node.get('example_output', 'N/A')}"
{correction_block}
Requirements for the prompt you write:
- It must instruct an LLM to analyze a conversation exchange
- It must include the literal text {{user_message}} and {{assistant_response}} as placeholders
- It must tell the LLM to respond with JSON only
- It must be {word_limit}
- It must focus ONLY on this specific node+layer intersection
- It must match the output style: {layer['output_style']}

Respond with ONLY a JSON object containing one key "prompt" whose value is the prompt template string.
No markdown. No backticks. No explanation. Just the JSON object.

Example: {{"prompt": "Analyze the following conversation exchange and extract all physical details..."}}"""


# ---------------------------------------------------------------------------
# LLM Caller
# ---------------------------------------------------------------------------

def call_ollama(prompt: str, model: str) -> str:
    """Call Ollama chat endpoint, return content string."""
    try:
        resp = requests.post(
            OLLAMA_CHAT_URL,
            json={
                "model": model,
                "messages": [
                    {
                        "role": "system",
                        "content": (
                            "You are a JSON generator. You respond with ONLY valid JSON objects. "
                            "No markdown, no backticks, no explanation, no preamble. "
                            "Just the raw JSON object starting with { and ending with }."
                        ),
                    },
                    {"role": "user", "content": prompt},
                ],
                "stream": False,
                "options": {
                    "temperature": 0.7,
                    "top_p": 0.9,
                    "num_predict": 2048,
                },
            },
            timeout=120,
        )
        resp.raise_for_status()
        data = resp.json()
        msg = data.get("message", {})
        result = msg.get("content", "")
        if not result and isinstance(msg, dict):
            result = msg.get("thinking", "")
        return result
    except requests.exceptions.ConnectionError:
        print(f"  ✗ Cannot connect to Ollama at {OLLAMA_CHAT_URL}")
        print("    Is Ollama running? Try: ollama serve")
        sys.exit(1)
    except requests.exceptions.Timeout:
        print("  ✗ Timed out after 120s")
        return ""
    except Exception as e:
        print(f"  ✗ Ollama error: {e}")
        return ""


# ---------------------------------------------------------------------------
# JSON Response Parser
# ---------------------------------------------------------------------------

def extract_prompt_from_response(raw: str) -> str:
    """Extract the prompt string from the LLM's JSON response."""
    if not raw:
        return ""

    cleaned = raw.strip()
    cleaned = re.sub(r'^```(?:json)?\s*', '', cleaned)
    cleaned = re.sub(r'\s*```$', '', cleaned)
    cleaned = cleaned.strip()

    # Strategy 1: Direct JSON parse
    try:
        data = json.loads(cleaned)
        if isinstance(data, dict) and "prompt" in data:
            return data["prompt"]
    except json.JSONDecodeError:
        pass

    # Strategy 2: Find outermost { } and parse
    start = cleaned.find("{")
    end = cleaned.rfind("}")
    if start >= 0 and end > start:
        try:
            data = json.loads(cleaned[start:end + 1])
            if isinstance(data, dict) and "prompt" in data:
                return data["prompt"]
        except json.JSONDecodeError:
            pass

    # Strategy 3: Regex for "prompt": "..."
    match = re.search(r'"prompt"\s*:\s*"((?:[^"\\]|\\.)*)"', cleaned, re.DOTALL)
    if match:
        try:
            return json.loads(f'"{match.group(1)}"')
        except (json.JSONDecodeError, ValueError):
            return match.group(1)

    # Strategy 4: If response looks like a usable prompt itself
    if len(cleaned) > MIN_PROMPT_LENGTH and "{user_message}" in cleaned.lower():
        return cleaned

    return ""


