def write_template(output_dir, node, layer, prompt_text, schema, generation_model):
    function_id = f"{node['id']}_{layer['id']}"
    proc = PROCESSING_MAP.get(layer["depth"], {"processing": "conscious", "critical_path": False})

    template = {
        "function_id": function_id,
        "node": node["id"],
        "node_name": node["name"],
        "node_domain": node["domain"],
        "layer": layer["id"],
        "layer_name": layer["name"],
        "depth": layer["depth"],
        "model_tier": layer["model_tier"],
        "runtime_models": MODEL_TIER_MAP.get(layer["model_tier"], []),
        "processing": proc["processing"],
        "critical_path": proc["critical_path"],
        "generated_at": datetime.now().isoformat(),
        "generated_by": generation_model,
        "prompt": prompt_text,
        "output_schema": schema,
    }

    filepath = output_dir / f"{function_id}.yaml"
    with open(filepath, "w") as f:
        f.write(f"# AUTO-GENERATED — Arcturian Grid Function Template\n")
        f.write(f"# Node: {node['id']} | Layer: {layer['id']} | ID: {function_id}\n")
        f.write(f"# Domain: {node['domain']}\n")
        f.write(f"# Depth: {layer['depth']} ({layer['name']})\n")
        f.write(f"# Generated: {datetime.now().strftime('%Y-%m-%d %H:%M')} | Model: {generation_model}\n")
        f.write(f"# ---\n\n")
        yaml.dump(template, f, default_flow_style=False, sort_keys=False, allow_unicode=True, width=120)

    return filepath


# ---------------------------------------------------------------------------
# Grid Index
# ---------------------------------------------------------------------------

def write_grid_index(output_dir, nodes, layers):
    index = {
        "arcturian_grid": {
            "version": "1.0",
            "generated_at": datetime.now().isoformat(),
            "total_functions": len(nodes) * len(layers),
            "nodes": [n["id"] for n in nodes],
            "layers": [l["id"] for l in layers],
            "matrix": {},
        }
    }
    for node in nodes:
        index["arcturian_grid"]["matrix"][node["id"]] = {}
        for layer in layers:
            fid = f"{node['id']}_{layer['id']}"
            index["arcturian_grid"]["matrix"][node["id"]][layer["id"]] = {
                "function_id": fid,
                "model_tier": layer["model_tier"],
                "processing": PROCESSING_MAP.get(layer["depth"], {}).get("processing", "conscious"),
                "template_file": f"{fid}.yaml",
            }
    filepath = output_dir / "grid_index.yaml"
    with open(filepath, "w") as f:
        f.write("# Arcturian Grid — Function Index\n")
        f.write(f"# Generated: {datetime.now().strftime('%Y-%m-%d %H:%M')}\n")
        f.write(f"# Total Functions: {len(nodes) * len(layers)}\n\n")
        yaml.dump(index, f, default_flow_style=False, sort_keys=False, width=120)
    return filepath


# ---------------------------------------------------------------------------
# Broken Template Detection
# ---------------------------------------------------------------------------

def find_broken_templates(output_dir: Path) -> list[tuple[str, str]]:
    """Find templates with prompts shorter than MIN_PROMPT_LENGTH."""
    broken = []
    for f in sorted(output_dir.glob("*.yaml")):
        if f.name == "grid_index.yaml":
            continue
        try:
            with open(f) as fh:
                data = yaml.safe_load(fh)
            prompt = str(data.get("prompt", ""))
            if len(prompt) < MIN_PROMPT_LENGTH:
                broken.append((data["node"], data["layer"]))
        except Exception:
            parts = f.stem.split("_", 1)
            if len(parts) == 2:
                broken.append((parts[0], parts[1]))
    return broken


# ---------------------------------------------------------------------------
# Main Generation Loop
# ---------------------------------------------------------------------------

def generate_grid(
    nodes_path, layers_path, output_dir, model,
    corrections_path=None, filter_nodes=None, filter_layers=None,
    dry_run=False, verbose=False, retry_broken=False, max_retries=3,
):
    print("=" * 60)
    print("  ARCTURIAN GRID — Template Generator")
    print("=" * 60)
    print(f"  Model:       {model}")
    print(f"  Output:      {output_dir}")
    print(f"  Corrections: {corrections_path or 'None'}")
    print(f"  Dry run:     {dry_run}")
    print(f"  Retry mode:  {retry_broken}")
    print(f"  Max retries: {max_retries}")
    print("=" * 60)

    nodes = load_nodes(nodes_path)
    layers = load_layers(layers_path)
    corrections = load_corrections(corrections_path) if corrections_path else []

    node_map = {n["id"]: n for n in nodes}
    layer_map = {l["id"]: l for l in layers}

    if retry_broken:
        cells = find_broken_templates(output_dir)
        print(f"\n  Found {len(cells)} broken templates to retry")
    else:
        if filter_nodes:
            nodes = [n for n in nodes if n["id"] in filter_nodes]
        if filter_layers:
            layers = [l for l in layers if l["id"] in filter_layers]
        cells = [(n["id"], l["id"]) for n in nodes for l in layers]

    total = len(cells)
    if total == 0:
        print("\n  Nothing to generate!")
        return 0, 0

    print(f"  Generating {total} templates")
    if corrections:
        print(f"  Applying {len(corrections)} correction rules")
    print()

    output_dir.mkdir(parents=True, exist_ok=True)

    generated = 0
    failed = 0
    start_time = time.time()
    current_node = None

    for idx, (node_id, layer_id) in enumerate(cells):
        node = node_map[node_id]
        layer = layer_map[layer_id]
        function_id = f"{node_id}_{layer_id}"
        prefix = f"    {idx+1:3d}/{total} {function_id:30s}"

        if node_id != current_node:
            current_node = node_id
            print(f"  [{node_id}]")

        applicable = get_applicable_corrections(
            corrections, node_id, layer_id, function_id, layer["model_tier"]
        )

        schema = build_schema(node_id)

        if dry_run:
            prompt_text = generate_fallback_prompt(node, layer)
            gen_model = "fallback"
        else:
            prompt_text = ""
            gen_model = "fallback"

            for attempt in range(max_retries):
                meta_prompt = build_meta_prompt(node, layer, applicable)
                if verbose:
                    suffix = f" (attempt {attempt+1}/{max_retries})" if attempt > 0 else ""
                    print(f"{prefix} — calling {model}...{suffix}")

                raw = call_ollama(meta_prompt, model)
                prompt_text = extract_prompt_from_response(raw)

                if len(prompt_text) >= MIN_PROMPT_LENGTH:
                    gen_model = model
                    break
                elif verbose and attempt < max_retries - 1:
                    print(f"{prefix}   ↳ got {len(prompt_text)} chars, retrying...")

            if len(prompt_text) < MIN_PROMPT_LENGTH:
                prompt_text = generate_fallback_prompt(node, layer)
                gen_model = "fallback"
                failed += 1

        write_template(output_dir, node, layer, prompt_text, schema, gen_model)
        generated += 1
        status = "✓" if gen_model != "fallback" else "~ (fallback)"
        print(f"{prefix} {status}")

    write_grid_index(output_dir, list(node_map.values()), list(layer_map.values()))

    elapsed = time.time() - start_time
    print()
    print("=" * 60)
    print(f"  COMPLETE")
    print(f"  Generated: {generated} templates")
    if failed:
        print(f"  Fallbacks: {failed}")
    else:
        print(f"  Fallbacks: 0 — all generated by LLM ✓")
    print(f"  Time:      {elapsed:.1f}s ({elapsed/max(generated,1):.1f}s per template)")
    print(f"  Output:    {output_dir}")
    print("=" * 60)

    remaining = find_broken_templates(output_dir)
    if remaining:
        print(f"\n  ⚠  {len(remaining)} templates still under {MIN_PROMPT_LENGTH} chars:")
        for nid, lid in remaining[:10]:
            print(f"      {nid}_{lid}")
        if len(remaining) > 10:
            print(f"      ... and {len(remaining)-10} more")
        print(f"  Run: python generate_grid.py --retry-broken")
    else:
        print(f"\n  ✓ All templates have prompts >= {MIN_PROMPT_LENGTH} chars")

    return generated, failed


