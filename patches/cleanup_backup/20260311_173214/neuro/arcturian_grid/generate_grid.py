def build_schema(node_id: str) -> dict:
    """Build output schema deterministically. No LLM needed."""
    props = dict(BASE_SCHEMA_FIELDS)
    props.update(NODE_SCHEMA_FIELDS.get(node_id, {}))
    return {
        "type": "object",
        "properties": props,
        "required": ["summary", "confidence", "flags"],
    }


